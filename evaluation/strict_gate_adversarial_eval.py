def audit(item: dict, *, model: str, base_url: str, key: str) -> dict:
    result = {k: value for k, value in item.items() if k != "chunks"}
    before = strict_gate(item["answer"], item["sources"], item["chunks"],
                         paper_ids=item["paper_ids"])
    result["precheck"] = before
    result["final"] = before
    result["status"] = "completed_no_call"
    if before["action"] == "verify":
        if not key:
            result["status"] = "pending_call"
            return result
        payload = {"question": item["question"], "retrieval_question": item["question"],
                   "proposed_answer": item["answer"], "paper_ids": item["paper_ids"],
                   "cited_chunks": [chunk for chunk in item["chunks"]
                                    if chunk["chunk_id"] in item["sources"]]}
        try:
            response = call_verifier(model=model, base_url=base_url, key=key, payload=payload)
            result["verifier"] = response
            result["final"] = strict_gate(item["answer"], item["sources"], item["chunks"],
                                          paper_ids=item["paper_ids"], verdict=json.loads(response["raw"]))
            result["status"] = "completed_called"
        except (OSError, RuntimeError, ValueError, TypeError, KeyError, IndexError) as exc:
            result["status"] = "call_failed"
            result["final"] = {"action": "abstain", "reason": "verifier_unavailable"}
            result["call_error_type"] = type(exc).__name__
    result["matched_expected"] = result["final"]["action"] == item["expected"]
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    model = os.getenv("DEEPSEEK_MODEL", "deepseek-chat")
    base_url = os.getenv("DEEPSEEK_BASE_URL", "https://api.deepseek.com")
    key = os.getenv("DEEPSEEK_API_KEY", "")
    args.output.mkdir(parents=True, exist_ok=True)
    manifest = {"protocol": "constructed-answer-evidence-pairs-v1",
                "fixtures_sha256": digest(DEFAULT_ANSWERS / "manifest.json"),
                "gate_sha256": digest(ROOT / "rag_reader/support_gate.py"),
                "prompt_sha256": digest(ROOT / "rag_reader/prompts.py"),
                "model": model, "base_url": base_url, "case_ids": [item["id"] for item in cases()],
                "scope": "constructed counterexamples and controls, not generated RAG answers"}
    manifest_path = args.output / "manifest.json"
    if manifest_path.exists():
        if json.loads(manifest_path.read_text(encoding="utf-8")) != manifest:
            raise ValueError("Inputs changed; choose a fresh output directory")
    else:
        atomic_json(manifest_path, manifest)
    for item in cases():
        path = args.output / (item["id"] + ".json")
        if path.exists():
            continue
        record = audit(item, model=model, base_url=base_url, key=key)
        atomic_json(path, record)
        print(f'{item["id"]}: {record["status"]} / {record["final"]["reason"]} '
              f'/ matched={record["matched_expected"]}', flush=True)
    records = [json.loads((args.output / (item["id"] + ".json")).read_text(encoding="utf-8"))
               for item in cases()]
    report = {"cases": len(records),
              "completed": sum(item["status"].startswith("completed") for item in records),
              "matched": sum(item.get("matched_expected") is True for item in records),
              "wrong_accepted": [item["id"] for item in records if item["expected"] == "abstain"
                                 and item["final"]["action"] == "answer"],
              "correct_refused": [item["id"] for item in records if item["expected"] == "answer"
                                  and item["final"]["action"] != "answer"],
              "verifier_calls": sum(item["status"] == "completed_called" for item in records),
              "prompt_tokens": sum(int(item.get("verifier", {}).get("usage", {}).get("prompt_tokens") or 0)
                                   for item in records),
              "completion_tokens": sum(int(item.get("verifier", {}).get("usage", {}).get("completion_tokens") or 0)
                                       for item in records),
              "verifier_seconds_total": round(sum(item.get("verifier", {}).get("seconds", 0)
                                                  for item in records), 4)}
    atomic_json(args.output / "report.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
